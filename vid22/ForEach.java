package vid22;

public class ForEach {
  public static void main(String[] args) {
    // For Each adalah statement yang digunakan untuk melakukan perulangan pada array
    // for(type variable : array) {
      // body
    // }

    String[] names = {"Fakhry", "Haidar", "Eko", "Kurniawan"};
    for(String name : names) {
      System.out.println(name);
    }
  }
  
}
