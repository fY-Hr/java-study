package vid23;

public class Method { 
  /*
    Method adalah sebuah blok kode yang dapat digunakan kembali.
    Method dapat menerima parameter dan mengembalikan nilai.
    Method dapat dijalankan dengan memanggil nama method tersebut.
    Di bahasa pemrograman lain, method disebut dengan function.
  */

  public static void main(String[] args) {
    sayHelloWorld();
  }

  public static void sayHelloWorld() {
    System.out.println("Hello, World!");
  }
  
}
