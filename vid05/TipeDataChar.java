package vid05;

public class TipeDataChar {
  public static void main (String[] args){
    char f = 'F';
    char a = '4';
    char k = 'K';
    char h = 'h';
    char r = 'r';
    char y = 'y';

    System.out.println(f + "\n" + a + "\n" + k);
    System.out.print(h); // with print(), it will not create a new line
    System.out.print(r);
    System.out.println(y);
  }
}