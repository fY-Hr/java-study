package vid18;

public class ForLoop {
  public static void main(String[] args) {
    // FOr loop adalah statement yang digunakan untuk melakukan perulangan
    // for(init statement; condition; post statement) {
      // body
    // }

    for(int i = 0; i < 10; i++) {
      System.out.println(i + 1); // akan dijalankan sebanyak 10 kali
    }

    // init statement adalah statement yang akan dijalankan sebelum perulangan dimulai
    // condition adalah kondisi yang akan dijalankan setiap kali perulangan dijalankan
    // post statement adalah statement yang akan dijalankan setiap kali perulangan dijalankan

    // perulangan yang tidak akan berhenti:
    // for(;;) {
      // body
    // }
  }
  
}
